"""Write cleave/_build_version.py from ``git describe`` before a freeze.

Run from the repo root on a full clone (tags fetched). Fails when git cannot
describe the checkout, so a build never ships without knowing what it is.
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from cleave.build_version import STAMP_MODULE, format_version, git_describe  # noqa: E402


def main() -> int:
    describe = git_describe()
    if describe is None:
        print("git describe failed; fetch tags (fetch-depth: 0)", file=sys.stderr)
        return 1
    STAMP_MODULE.write_text(
        '"""Generated by scripts/stamp_build_version.py. Do not commit."""\n\n'
        f"DESCRIBE = {describe!r}\n",
        encoding="utf-8",
    )
    print(f"stamped {describe} -> {format_version(describe)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
